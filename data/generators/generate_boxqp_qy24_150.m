function [manifest, audit] = generate_boxqp_qy24_150()
%GENERATE_BOXQP_QY24_150 Generate and certify 75 QY24 BoxQPs at each size.
%   [manifest,audit] = generate_boxqp_qy24_150()
%   Saves n=25 and n=50, seeds 1:75, beneath
%   data/structured/generated/qy24_boxqp_150.
%   These are MATLAB-generated instances following Qiu--Yildirim (2024),
%   Algorithm 2 and Section 6.2 sampling, not copies of the authors' files.
%   Every instance has a strictly inexact RLT relaxation. SDP-RLT
%   inexactness is not guaranteed and the QP optimum is not planted.

cfg = struct('suite_name','qy24_boxqp_150', 'families',{{'boxqp_inexact'}}, ...
    'sizes',[25 50], 'seeds',1:75, ...
    'generator_options',struct('boxqp_inexact',struct('parameter_max',10)));
manifest = generate_structured_suite(cfg);
assert(numel(manifest)==150 && sum([manifest.n]==25)==75 && ...
    sum([manifest.n]==50)==75 && ...
    numel(unique({manifest.id}))==150, 'dcqp:boxqpSuite', ...
    'The BoxQP suite must have 75 distinct cases at each dimension.');

audit = repmat(struct('id','','n',0,'seed',0,'rlt_optimum',NaN, ...
    'proven_qp_minus_rlt_gap',NaN,'distinguished_index',0, ...
    'Wkk',NaN,'Zkk',NaN),numel(manifest),1);
for j = 1:numel(manifest)
    entry = manifest(j);
    data = load(entry.file,'instance'); p = data.instance;
    a = p.certificate; n = entry.n; k = p.metadata.distinguished_index;
    x = a.rlt_x; X = a.rlt_X; e = ones(n,1);
    tol = 1e-10*max(1,norm(p.Q,'inf')+norm(p.c,'inf'));
    assert(isequal(size(p.Q),[n n]) && isequal(size(p.c),[n 1]) ...
        && norm(p.Q-p.Q','inf')<=tol ...
        && isequal(p.A,[-eye(n);eye(n)]) ...
        && isequal(p.b,[zeros(n,1);e]) ...
        && isempty(p.Aeq) && isempty(p.beq) ...
        && isequal(p.LB,zeros(n,1)) && isequal(p.UB,e), ...
        'dcqp:boxqpSuite','Invalid BoxQP dimensions or box constraints.');
    assert(strcmp(p.metadata.family,'boxqp_inexact') ...
        && p.metadata.seed==entry.seed ...
        && p.metadata.parameter_max==10 ...
        && p.metadata.rlt_inexact_guaranteed ...
        && ~p.metadata.sdp_rlt_inexact_guaranteed ...
        && isnan(p.metadata.known_optimum) ...
        && isempty(p.metadata.known_solution), ...
        'dcqp:boxqpSuite','Invalid BoxQP metadata.');
    assert(all(isfinite(p.Q(:))) && all(isfinite(p.c)) ...
        && all([a.r;a.s;a.W(:);a.Y(:);a.Z(:)]>=0) ...
        && norm(2*p.Q-a.W+a.Y+a.Y'-a.Z,'inf')<=tol ...
        && norm(p.c+a.r-a.s+a.W*e-a.Y'*e,'inf')<=tol, ...
        'dcqp:boxqpSuite','Invalid Algorithm 2 coefficients.');
    assert(all(x>=0) && all(x<=1) && norm(X-X','inf')<=tol ...
        && min(X(:))>=-tol && min(reshape(e*x'-X,[],1))>=-tol ...
        && min(reshape(X-x*e'-e*x'+e*e',[],1))>=-tol, ...
        'dcqp:boxqpSuite','Invalid RLT primal witness.');
    primal = sum(sum(p.Q.*X))+p.c'*x;
    dual = -sum(a.r)-0.5*sum(a.W(:));
    assert(abs(primal-dual)<=tol ...
        && abs(dual-p.metadata.known_rlt_optimum)<=tol ...
        && a.W(k,k)>0 && a.Z(k,k)>0 ...
        && x(k)==0.5 && X(k,k)==0, ...
        'dcqp:boxqpSuite','Invalid RLT optimum or strict-gap witness.');
    % The k-th diagonal terms alone bound every feasible QP objective
    % above the RLT optimum by this positive amount.
    w = a.W(k,k); z = a.Z(k,k);
    audit(j) = struct('id',entry.id,'n',n,'seed',entry.seed, ...
        'rlt_optimum',dual,'proven_qp_minus_rlt_gap',w*z/(2*(w+z)), ...
        'distinguished_index',k,'Wkk',w,'Zkk',z);
end

folder = fileparts(manifest(1).file);
save(fullfile(folder,'validation.mat'),'audit');
writetable(struct2table(audit,'AsArray',true), ...
    fullfile(folder,'validation.csv'));
fprintf('Validated %d QY24 BoxQPs (75 at n=25, 75 at n=50); ',numel(audit));
fprintf('minimum proven QP-RLT gap %.6g.\n', ...
    min([audit.proven_qp_minus_rlt_gap]));
end
